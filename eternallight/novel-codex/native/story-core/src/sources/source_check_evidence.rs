//! Exact, currently selected source text for model-owned checks. This proves
//! provenance and quotations, never the truth of a model's literary assessment.
use crate::{ProjectId, RepositoryError, authoring_runs::storage_error};
use rusqlite::{Connection, OptionalExtension, params};
use serde::{Deserialize, Serialize};
use serde_json::Value;

#[derive(Clone, Serialize, Deserialize, ts_rs::TS)]
#[ts(export)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct SourceCheck {
    pub source_id: String,
    pub revision_id: String,
    pub content_hash: String,
    pub evidence: Value,
}

fn invalid(message: &str) -> RepositoryError {
    RepositoryError::InvalidContent(format!("sourceChecks: {message}"))
}

// Sources may project body as sceneGroups. Reconstruct only text already
// admitted by the source builder; never use the unprojected revision to grant
// access to hidden scenes or points of view.
fn texts(value: &Value, found: &mut Vec<String>) {
    match value {
        Value::String(text) => found.push(text.clone()),
        Value::Array(items) => {
            for item in items {
                texts(item, found);
            }
        }
        Value::Object(fields) => {
            if let Some(body) = value["body"].as_str() {
                found.push(body.to_owned());
                return;
            } else if let Some(groups) = value["sceneGroups"].as_array() {
                let bodies: Option<Vec<&str>> =
                    groups.iter().map(|group| group["body"].as_str()).collect();
                if let Some(bodies) = bodies {
                    found.push(
                        bodies
                            .iter()
                            .map(|body| body.trim())
                            .collect::<Vec<_>>()
                            .join("\n\n---\n\n"),
                    );
                    return;
                }
            }
            for (key, child) in fields {
                if !matches!(
                    key.as_str(),
                    "body"
                        | "sceneGroups"
                        | "revisionId"
                        | "sourceRevisionId"
                        | "objectId"
                        | "authority"
                        | "sourceAuthority"
                        | "workingSelectionRevision"
                ) {
                    texts(child, found);
                }
            }
        }
        _ => {}
    }
}

pub(crate) fn validate(
    db: &Connection,
    project: &ProjectId,
    work: &str,
    check: &SourceCheck,
) -> Result<(), RepositoryError> {
    if check.source_id.is_empty()
        || check.source_id.len() > 160
        || check.revision_id.is_empty()
        || check.revision_id.len() > 160
        || check.content_hash.len() != 64
        || !check
            .content_hash
            .bytes()
            .all(|byte| byte.is_ascii_hexdigit() && !byte.is_ascii_uppercase())
    {
        return Err(invalid(
            "copy exact source identity and hash from the authorized catalogue",
        ));
    }
    let hash: Option<String> = db.query_row(
        "SELECT i.content_hash FROM story_task_source_items_v2 i JOIN story_tasks_v2 t ON t.task_id=i.task_id JOIN story_work_attempts_v1 a ON a.attempt_id=t.task_id JOIN story_work_steps_v1 s ON s.id=a.step_id WHERE i.source_id=?1 AND t.project_id=?2 AND s.work_task_id=?3",
        params![check.source_id,project.as_str(),work], |row| row.get(0),
    ).optional().map_err(storage_error)?;
    let hash = hash.ok_or(RepositoryError::TaskOutputForbidden)?;
    if hash != check.content_hash {
        return Err(RepositoryError::TaskInputStale);
    }
    // Select paths generated by SQLite from the admitted catalogue, never a
    // caller-supplied JSON pointer. A large book catalogue need not be copied
    // into Rust just to verify one current chapter quotation.
    let mut query=db.prepare("SELECT CASE WHEN length(CAST(json_extract(i.payload_json,j.path) AS BLOB))<=8388608 THEN json_extract(i.payload_json,j.path) END FROM story_task_source_items_v2 i,json_tree(i.payload_json) j WHERE i.source_id=?1 AND j.type='text' AND j.key IN ('sourceRevisionId','revisionId') AND j.atom=?2 LIMIT 65").map_err(storage_error)?;
    let selected = query
        .query_map(params![check.source_id, check.revision_id], |row| {
            row.get::<_, Option<String>>(0)
        })
        .map_err(storage_error)?;
    let mut records = Vec::new();
    for record in selected {
        let record = record
            .map_err(storage_error)?
            .ok_or_else(|| invalid("source record exceeds the bounded verification size"))?;
        records.push(
            serde_json::from_str::<Value>(&record).map_err(|_| RepositoryError::CorruptState)?,
        );
    }
    if records.len() > 64 {
        return Err(invalid("too many records for one revision"));
    }
    if records.is_empty() {
        return Err(invalid("revision is not part of this authorized source"));
    }
    let revision: Option<(String, String, Option<String>, Option<String>, Option<String>, Option<i64>)> = db.query_row(
        "SELECT r.object_id,r.content_json,h.candidate_revision_id,h.accepted_revision_id,b.revision_id,b.selection_revision FROM story_revisions_v2 r JOIN story_object_heads_v2 h ON h.project_id=r.project_id AND h.object_id=r.object_id LEFT JOIN story_working_baselines_v2 b ON b.project_id=h.project_id AND b.object_kind=h.object_kind AND b.object_id=CASE WHEN h.object_kind='draft' THEN substr(h.object_id,7) ELSE h.object_kind END WHERE r.project_id=?1 AND r.revision_id=?2",
        params![project.as_str(),check.revision_id], |row| Ok((row.get(0)?,row.get(1)?,row.get(2)?,row.get(3)?,row.get(4)?,row.get(5)?)),
    ).optional().map_err(storage_error)?;
    let (object, content, candidate, accepted, working, selection) =
        revision.ok_or(RepositoryError::TaskInputStale)?;
    let quote = check.evidence["quote"]
        .as_str()
        .ok_or_else(|| invalid("provide an exact source quote"))?;
    if !quote_returned(db, check)? {
        return Err(invalid(
            "read this exact source quote as the root task before citing it; catalogue/index/child reading is not root reading",
        ));
    }
    let frozen_comparison = records
        .iter()
        .any(|record| record["authority"] == "frozenComparison")
        && crate::task_workspace::frozen_comparison(
            db,
            &check.source_id,
            project.as_str(),
            &check.revision_id,
        )?;
    let current = records.iter().any(|record| {
        if record["objectId"].as_str().is_some_and(|id| id != object) {
            return false;
        }
        let selected = if let Some(frozen_selection) = record["workingSelectionRevision"].as_i64() {
            if selection != Some(frozen_selection) {
                return false;
            }
            working.as_deref()
        } else if record["authority"] == "accepted" || record["sourceAuthority"] == "accepted" {
            accepted.as_deref()
        } else {
            candidate.as_deref().or(accepted.as_deref())
        };
        if !(record["authority"] == "frozenComparison" && frozen_comparison)
            && selected != Some(check.revision_id.as_str())
        {
            return false;
        }
        let mut visible = Vec::new();
        texts(record.get("content").unwrap_or(record), &mut visible);
        visible.iter().any(|text| text.contains(quote))
    });
    if !current {
        return Err(invalid(
            "source selection changed or the quote is outside the authorized text projection",
        ));
    }
    let content: Value =
        serde_json::from_str(&content).map_err(|_| RepositoryError::CorruptState)?;
    if let Some(body) = content["body"].as_str() {
        crate::source_evidence::resolve(&check.evidence, body)?;
    } else {
        let mut candidates = Vec::new();
        texts(&content, &mut candidates);
        let matching: Vec<_> = candidates
            .iter()
            .filter(|text| text.contains(quote))
            .collect();
        if matching.len() != 1 {
            return Err(invalid("quote must identify one exact source text field"));
        }
        crate::source_evidence::resolve(&check.evidence, matching[0])?;
    }
    Ok(())
}

// A cached projection is visibility authority, not a transport receipt. Verify
// a quoted field/range was actually returned to root, without copying a book.
pub(crate) fn quote_returned(
    db: &Connection,
    check: &SourceCheck,
) -> Result<bool, RepositoryError> {
    let mut raw=db.prepare("SELECT start_byte,end_byte,total_bytes FROM story_task_source_raw_returns_v1 WHERE source_id=?1 AND content_hash=?2 ORDER BY start_byte,end_byte").map_err(storage_error)?;
    let mut through = 0usize;
    let mut total = 0usize;
    for row in raw
        .query_map(params![check.source_id, check.content_hash], |r| {
            Ok((
                r.get::<_, usize>(0)?,
                r.get::<_, usize>(1)?,
                r.get::<_, usize>(2)?,
            ))
        })
        .map_err(storage_error)?
    {
        let (start, end, n) = row.map_err(storage_error)?;
        total = n;
        if start <= through {
            through = through.max(end)
        }
    }
    if total > 0 && through == total {
        return Ok(true);
    }
    // A complete parsed source exposes the same admitted text as a complete raw
    // source, including exact quotes spanning scene groups. Partial field reads
    // below still prove only their own returned ranges. validate() separately
    // checks the quote and revision against the authorized projection.
    let mut pages=db.prepare("SELECT from_entry,to_entry,total_entries FROM story_task_source_returned_v1 WHERE source_id=?1 AND content_hash=?2 ORDER BY from_entry,to_entry").map_err(storage_error)?;
    let (mut through,mut total)=(0usize,0usize);
    for row in pages.query_map(params![check.source_id,check.content_hash],|row|Ok((row.get::<_,usize>(0)?,row.get::<_,usize>(1)?,row.get::<_,usize>(2)?))).map_err(storage_error)? {
        let (start,end,n)=row.map_err(storage_error)?;
        if total!=0 && total!=n {return Err(RepositoryError::CorruptState);}
        if end>n || start>=end {return Err(RepositoryError::CorruptState);}
        total=n;if start<=through {through=through.max(end);}
    }
    if total>0 && through==total {return Ok(true);}
    let mut query=db.prepare("SELECT field_ranges_json FROM story_task_source_returned_v1 WHERE source_id=?1 AND content_hash=?2 LIMIT 10001").map_err(storage_error)?;
    let mut ranges = std::collections::BTreeMap::<String, Vec<(usize, usize)>>::new();
    let mut count = 0;
    for row in query
        .query_map(params![check.source_id, check.content_hash], |r| {
            r.get::<_, String>(0)
        })
        .map_err(storage_error)?
    {
        count += 1;
        if count > 10000 {
            return Err(invalid("source receipt limit exceeded"));
        }
        let fields: Value = serde_json::from_str(&row.map_err(storage_error)?)
            .map_err(|_| RepositoryError::CorruptState)?;
        for field in fields.as_array().ok_or(RepositoryError::CorruptState)? {
            let path = field["path"]
                .as_str()
                .ok_or(RepositoryError::CorruptState)?;
            if path.rsplit('/').next().is_some_and(|key| {
                matches!(
                    key,
                    "id" | "title"
                        | "objectId"
                        | "revisionId"
                        | "sourceRevisionId"
                        | "chapterId"
                        | "chapterNumber"
                        | "authority"
                        | "sourceAuthority"
                        | "purpose"
                        | "workingSelectionRevision"
                )
            }) {
                continue;
            }
            ranges.entry(path.into()).or_default().push((
                field["characterRange"]["start"].as_u64().unwrap_or(0) as usize,
                field["characterRange"]["end"]
                    .as_u64()
                    .map(|n| n as usize)
                    .unwrap_or(usize::MAX),
            ));
        }
    }
    for (pointer, mut ranges) in ranges {
        let mut path = String::from("$");
        for part in pointer.split('/').skip(1) {
            let part = part.replace("~1", "/").replace("~0", "~");
            if let Ok(index) = part.parse::<usize>() {
                path.push_str(&format!("[{index}]"))
            } else {
                path.push('.');
                path.push_str(
                    &serde_json::to_string(&part).map_err(|_| RepositoryError::CorruptState)?,
                );
            }
        }
        let text:Option<String>=db.query_row("SELECT CASE WHEN json_type(payload_json,?2)='text' AND length(CAST(json_extract(payload_json,?2) AS BLOB))<=8388608 THEN json_extract(payload_json,?2) END FROM story_task_source_items_v2 WHERE source_id=?1",params![check.source_id,path],|r|r.get(0)).optional().map_err(storage_error)?.flatten();
        let Some(text) = text else { continue };
        let Ok(anchor) = crate::source_evidence::resolve(&check.evidence, &text) else {
            continue;
        };
        let start = anchor["start"]
            .as_u64()
            .ok_or(RepositoryError::CorruptState)? as usize;
        let end = anchor["end"]
            .as_u64()
            .ok_or(RepositoryError::CorruptState)? as usize;
        ranges.sort_unstable();
        let mut through = start;
        for (from, to) in ranges {
            if from <= through {
                through = through.max(to)
            }
        }
        if through >= end {
            return Ok(true);
        }
    }
    Ok(false)
}

pub(crate) fn current(
    db: &Connection,
    project: &ProjectId,
    work: &str,
    check: &SourceCheck,
) -> Result<bool, RepositoryError> {
    match validate(db, project, work, check) {
        Ok(()) => Ok(true),
        Err(
            RepositoryError::InvalidContent(_)
            | RepositoryError::TaskInputStale
            | RepositoryError::TaskOutputForbidden
            | RepositoryError::TaskBindingInvalid,
        ) => Ok(false),
        Err(error) => Err(error),
    }
}

