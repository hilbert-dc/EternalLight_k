import assert from 'node:assert/strict';
import test from 'node:test';
import {randomUUID} from 'node:crypto';
import {readFile} from 'node:fs/promises';
import {transform} from 'esbuild';
import {registerProjectArtifactHandlers} from '../project-artifact-handlers.mjs';
import {nativeRuntimeFixture} from './helpers/native-runtime-fixture.mjs';
const {code}=await transform(await readFile(new URL('../../src/merge-chapter-draft.ts',import.meta.url),'utf8'),{loader:'ts',format:'esm'});
const {mergeChapterDraft}=await import(`data:text/javascript;base64,${Buffer.from(code).toString('base64')}`);
test('chapter scene merge saves through Native CAS and stale writers cannot overwrite it',{timeout:360_000},async t=>{
 const runtime=await nativeRuntimeFixture(t);
 const {project}=await runtime.request('/api/projects',{title:'章节并行编辑',logline:'',medium:'novel',idempotencyKey:randomUUID()});
 const root=`/api/projects/${project.id}`;
 const read=()=>runtime.request(`${root}/creative-workspace`);
 const save=(workspace,draft)=>runtime.request(`${root}/drafts/checkpoints`,{expectedRevision:workspace.revision,expectedCandidateRevisionId:workspace.chapters[0]?.candidate?.id??null,idempotencyKey:randomUUID(),payload:{chapterId:'chapter-1',chapterNumber:1,title:draft.title,body:draft.sceneGroups.map(s=>s.body).join('\n\n---\n\n'),sceneGroups:draft.sceneGroups.map(s=>({id:s.id,sceneId:s.sceneId??null,body:s.body,locked:Boolean(s.locked)}))}});
 const initial=await read();
 await save(initial,{title:'雨夜',sceneGroups:[{id:'a',sceneId:null,body:'第一场在门口。'},{id:'b',sceneId:null,body:'第二场在灯下。'}]});
 const baseWorkspace=await read(),base=baseWorkspace.chapters[0].candidate;
 const handlers=new Map();
 registerProjectArtifactHandlers({handle:(name,handler)=>handlers.set(name,handler)},path=>runtime.request(path));
 const history=await handlers.get('runtime:get-chapter-draft-history')({},project.id,'chapter-1',base.id);
 assert.equal(history.projectId,project.id);assert.deepEqual(history.revision,base);
 await assert.rejects(runtime.request(`${root}/chapters/another-chapter/revisions/${base.id}`),/404|409/);
 const {project:other}=await runtime.request('/api/projects',{title:'另一作品',logline:'',medium:'novel',idempotencyKey:randomUUID()});
 await assert.rejects(runtime.request(`/api/projects/${other.id}/chapters/chapter-1/revisions/${base.id}`),/404|409/);

 const local=structuredClone(base),remote=structuredClone(base);
 local.sceneGroups[0].body='作者改写了门口的场景。';remote.sceneGroups[1].body='后台改写了灯下的场景。';
 await save(baseWorkspace,remote);const updated=await read();
 await assert.rejects(save(baseWorkspace,local),/409/);
 const merged=mergeChapterDraft(base,local,updated.chapters[0].candidate);assert.ok(merged,JSON.stringify({base,remote:updated.chapters[0].candidate}));
 const receipt=await save(updated,merged);const final=await read();
 assert.equal(final.chapters[0].candidate.id,receipt.revisionId);
 assert.deepEqual(final.chapters[0].candidate.sceneGroups.map(s=>s.body),[local.sceneGroups[0].body,remote.sceneGroups[1].body]);
 await assert.rejects(save(updated,remote),/409/);
 assert.equal((await read()).chapters[0].candidate.id,receipt.revisionId);
 assert.equal(final.chapters[0].accepted,null,'saving must not publish');
 assert.deepEqual((await runtime.request(`${root}/chapters/chapter-1/revisions/${base.id}`)).revision,base,'historical baseline changed after newer saves');
 const structuralBase=final.chapters[0].candidate;
 const author=structuredClone(structuralBase),background=structuredClone(structuralBase);
 author.sceneGroups[0].body='结构变化期间保留的作者正文。';
 background.sceneGroups.reverse();background.sceneGroups.push({id:'new-scene',sceneId:null,body:'后台新增第三场。',locked:false});
 await save(final,background);const structuralWorkspace=await read();
 const structuralMerge=mergeChapterDraft(structuralBase,author,structuralWorkspace.chapters[0].candidate);assert.ok(structuralMerge);
 await save(structuralWorkspace,structuralMerge);const structuralFinal=await read();
 assert.deepEqual(structuralFinal.chapters[0].candidate.sceneGroups.map(s=>s.body),[background.sceneGroups[0].body,author.sceneGroups[0].body,'后台新增第三场。']);
 await assert.rejects(save(structuralWorkspace,author),/409/);
 assert.equal(structuralFinal.chapters[0].accepted,null);

});
