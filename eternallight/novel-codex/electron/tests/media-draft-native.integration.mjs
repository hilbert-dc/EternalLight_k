import assert from 'node:assert/strict';
import test from 'node:test';
import { randomUUID } from 'node:crypto';
import { readFile } from 'node:fs/promises';
import { transform } from 'esbuild';
import { nativeRuntimeFixture } from './helpers/native-runtime-fixture.mjs';
import { MultimediaHost, registerMultimediaHandlers } from '../media-host.mjs';
const { code } = await transform(await readFile(new URL('../../src/multimedia/merge-media-draft.ts', import.meta.url), 'utf8'), { loader:'ts',format:'esm' });
const { mergeMediaDraft, resolveMediaDraft } = await import(`data:text/javascript;base64,${Buffer.from(code).toString('base64')}`);

test('merged local media edits preserve both Native revisions and still reject stale saves', {timeout:360_000}, async t => {
 const runtime=await nativeRuntimeFixture(t);
 const created=await runtime.request('/api/projects',{title:'草稿合并验收',logline:'',medium:'comic',idempotencyKey:randomUUID()});
 const project=created.project.id,edition=created.activeEditionId;
 const host=new MultimediaHost({runtimeRequest:(path,options={})=>runtime.request(path,options.body?JSON.parse(options.body):undefined,options.method??'GET'),directory:runtime.directory});
 const save=(workspace,document)=>host.save(project,edition,{expectedRevisionId:workspace.revisionId,document,idempotencyKey:randomUUID(),readSet:[],sources:workspace.sources});
 const empty=await host.workspace(project,edition);
 const doc=structuredClone(empty.document);
 doc.pages=['page-a','page-b'].map(id=>({id,title:id,width:1200,height:1600,readingDirection:'leftToRight',panels:[]}));
 const base=await save(empty,doc),local=structuredClone(base.document),remote=structuredClone(base.document);
 local.pages[0].title='作者正在编辑的第一页';remote.pages[1].title='后台保存的第二页';
 const savedRemote=await save(base,remote);
 await assert.rejects(save(base,local),/409/);
 const merged=mergeMediaDraft(base.document,local,savedRemote.document);assert.ok(merged);
 const savedMerged=await save(savedRemote,merged);
 assert.equal(savedMerged.document.pages[0].title,local.pages[0].title);
 assert.equal(savedMerged.document.pages[1].title,remote.pages[1].title);
 const handlers=new Map();registerMultimediaHandlers({handle:(name,handler)=>handlers.set(name,handler)},host);
 const historical=await handlers.get('media:read-workspace')({},project,edition,base.edition.branchId,savedRemote.revisionId);
 assert.equal(historical.revisionId,savedRemote.revisionId,'IPC must forward the exact historical revision');
 assert.deepEqual(historical.document,savedRemote.document,'merge must not rewrite the prior Native revision');
 const competing=structuredClone(savedMerged.document);competing.pages[0].title='更新的已保存改动';
 const latest=await save(savedMerged,competing);
 await assert.rejects(save(savedMerged,merged),/409/);
 assert.deepEqual((await host.workspace(project,edition)).document,latest.document);
 const authorConflict=structuredClone(savedMerged.document);authorConflict.pages[0].title='作者选择的第一页';
 authorConflict.pages[1].title='作者独立第二页';
 const resolved=resolveMediaDraft(savedMerged.document,authorConflict,latest.document,'remote');
 assert.ok(resolved);assert.equal(resolved.pages[0].title,latest.document.pages[0].title);
 assert.equal(resolved.pages[1].title,authorConflict.pages[1].title);
 const resolution=await save(latest,resolved);
 assert.deepEqual(resolution.document,resolved);
 assert.deepEqual((await host.workspace(project,edition,base.edition.branchId,latest.revisionId)).document,latest.document);
});
