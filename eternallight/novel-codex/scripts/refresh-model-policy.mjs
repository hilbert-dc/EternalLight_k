import { createHash } from "node:crypto";
import { spawnSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { readBuildIdentity, sha256File, verifyBuildIdentity } from "./build-provenance.mjs";
import { certificationPath } from "./certification-publication.mjs";

const root = fileURLToPath(new URL("..", import.meta.url));
const runtime = join(root, "codex-runtime");
const publicCatalogPath = join(runtime, "model-catalog.json");
const policyPath = join(runtime, "supported-cli.json");
const sha256 = (path) => createHash("sha256").update(readFileSync(path)).digest("hex");
const policy = JSON.parse(readFileSync(policyPath, "utf8"));
policy.modelCatalogSha256 = sha256(publicCatalogPath);
policy.modelCertificationsSha256 = sha256(certificationPath(runtime, policy));
delete policy.codexModelCatalogSha256;
const workspaceCli = resolve(root, `../../codex-rs/target/debug/codex${process.platform === "win32" ? ".exe" : ""}`);
if (!existsSync(workspaceCli)) throw new Error("当前源码构建的 Codex CLI 不存在，请先运行 cargo build -p codex-cli --bin codex");
const repositoryRoot = resolve(root, "../..");
const identityPath = join(runtime, "build-identities", `${process.platform}-${process.arch}.json`);
if (!existsSync(identityPath)) throw new Error("当前源码构建缺少 BuildIdentity，请先运行 npm run build:codex-runtime");
const identity = readBuildIdentity(identityPath);
verifyBuildIdentity(identity, workspaceCli, { repositoryRoot });
const version = spawnSync(workspaceCli, ["--version"], { encoding: "utf8", timeout: 15_000 });
if (version.status !== 0 || !policy.sources["workspace-build"].versions.includes(version.stdout.trim())) throw new Error("当前源码构建的 Codex CLI 版本不受支持");
policy.sources["workspace-build"].digests = { [`${process.platform}-${process.arch}`]: sha256(workspaceCli) };
policy.sources["workspace-build"].buildIdentities = { [`${process.platform}-${process.arch}`]: { identityId: identity.identityId, sha256: sha256File(identityPath) } };
writeFileSync(policyPath, `${JSON.stringify(policy, null, 2)}\n`);
